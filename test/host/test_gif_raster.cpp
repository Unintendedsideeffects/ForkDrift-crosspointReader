// Encoded by Pillow (an independent GIF encoder): 37x29, interlaced, 200 palette entries, so the LZW
// code width grows past 8 bits. Guards decoder and in-file fixture encoder against sharing one bug.
static uint32_t gifCrc32(const std::vector<uint8_t>& data) {
  uint32_t crc = 0xFFFFFFFFu;
  for (const uint8_t byte : data) {
    crc ^= byte;
    for (int bit = 0; bit < 8; bit++) crc = (crc >> 1) ^ (0xEDB88320u & (0u - (crc & 1u)));
  }
  return ~crc;
}

