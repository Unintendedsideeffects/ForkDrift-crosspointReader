struct BitWriter {
  std::vector<uint8_t> bytes;
  uint32_t acc = 0;
  int nbits = 0;

  void write(uint32_t code, int width) {
    acc |= code << nbits;
    nbits += width;
    while (nbits >= 8) {
      bytes.push_back(static_cast<uint8_t>(acc & 0xFF));
      acc >>= 8;
      nbits -= 8;
    }
  }

  void flush() {
    if (nbits > 0) {
      bytes.push_back(static_cast<uint8_t>(acc & 0xFF));
    }
    acc = 0;
    nbits = 0;
  }
};

struct DictEntry {
  int prefix;
  int suffix;
  int code;
};

int dictLookup(const std::vector<DictEntry>& table, int prefix, int suffix) {
  for (const DictEntry& entry : table) {
    if (entry.prefix == prefix && entry.suffix == suffix) {
      return entry.code;
    }
  }
  return -1;
}

std::vector<uint8_t> lzwCompress(const std::vector<uint8_t>& pixels, int minCodeSize) {
  const int clear = 1 << minCodeSize;
  const int eoi = clear + 1;
  int codeSize = minCodeSize + 1;
  int next = eoi + 1;
  std::vector<DictEntry> table;
  BitWriter bits;
  bits.write(static_cast<uint32_t>(clear), codeSize);
  int cur = pixels[0];
  for (size_t i = 1; i < pixels.size(); i++) {
    const int pix = pixels[i];
    const int found = dictLookup(table, cur, pix);
    if (found >= 0) {
      cur = found;
      continue;
    }
    bits.write(static_cast<uint32_t>(cur), codeSize);
    if (next < gifraster::kLzwCodeCount) {
      table.push_back(DictEntry{cur, pix, next});
      next++;
      // The decoder adds each entry one code later than the encoder (the first code after a clear
      // adds nothing), so a GIF encoder widens one code after `next` reaches 1 << codeSize.
      if (next > (1 << codeSize) && codeSize < 12) {
        codeSize++;
      }
    }
    cur = pix;
  }
  bits.write(static_cast<uint32_t>(cur), codeSize);
  bits.write(static_cast<uint32_t>(eoi), codeSize);
  bits.flush();
  return bits.bytes;
}

void appendSubBlocks(std::vector<uint8_t>& out, const std::vector<uint8_t>& data) {
  size_t i = 0;
  while (i < data.size()) {
    const size_t n = data.size() - i > 255 ? 255 : data.size() - i;
    out.push_back(static_cast<uint8_t>(n));
    out.insert(out.end(), data.begin() + static_cast<std::ptrdiff_t>(i),
               data.begin() + static_cast<std::ptrdiff_t>(i + n));
    i += n;
  }
  out.push_back(0);
}

void appendU16(std::vector<uint8_t>& out, uint16_t value) {
  out.push_back(static_cast<uint8_t>(value & 0xFF));
  out.push_back(static_cast<uint8_t>(value >> 8));
}

int tableBitsForCount(int count) {
  int bits = 0;
  while ((2 << bits) < count) {
    bits++;
  }
  return bits;
}

std::vector<uint8_t> interlaceOrder(const std::vector<uint8_t>& display, int width, int height) {
  static constexpr int kStart[4] = {0, 4, 2, 1};
  static constexpr int kStep[4] = {8, 8, 4, 2};
  std::vector<uint8_t> ordered;
  ordered.reserve(display.size());
  for (int pass = 0; pass < 4; pass++) {
    for (int y = kStart[pass]; y < height; y += kStep[pass]) {
      const int row = y * width;
      ordered.insert(ordered.end(), display.begin() + row, display.begin() + row + width);
    }
  }
  return ordered;
}

struct GifSpec {
  int width = 1;
  int height = 1;
  bool gif89 = false;
  bool interlaced = false;
  int transparent = -1;
  std::vector<uint8_t> gct;
  std::vector<uint8_t> lct;
  std::vector<uint8_t> pixels;
};

std::vector<uint8_t> buildGif(const GifSpec& spec) {
  const int gctCount = static_cast<int>(spec.gct.size() / 3);
  const int lctCount = static_cast<int>(spec.lct.size() / 3);
  const int gctBits = gctCount > 0 ? tableBitsForCount(gctCount) : 0;
  const int lctBits = lctCount > 0 ? tableBitsForCount(lctCount) : 0;
  const int gctSlots = gctCount > 0 ? (2 << gctBits) : 0;
  const int lctSlots = lctCount > 0 ? (2 << lctBits) : 0;
  int minCodeSize = 2;
  if (lctCount > 0) {
    minCodeSize = lctBits + 1;
  } else if (gctCount > 0) {
    minCodeSize = gctBits + 1;
  }
  if (minCodeSize < 2) {
    minCodeSize = 2;
  }

  std::vector<uint8_t> raster = spec.pixels;
  if (spec.interlaced) {
    raster = interlaceOrder(spec.pixels, spec.width, spec.height);
  }
  const std::vector<uint8_t> compressed = lzwCompress(raster, minCodeSize);

  std::vector<uint8_t> out;
  out.insert(out.end(), {'G', 'I', 'F', '8', static_cast<uint8_t>(spec.gif89 ? '9' : '7'), 'a'});
  appendU16(out, static_cast<uint16_t>(spec.width));
  appendU16(out, static_cast<uint16_t>(spec.height));
  uint8_t packedLsd = 0;
  if (gctCount > 0) {
    packedLsd = static_cast<uint8_t>(0x80 | gctBits);
  }
  out.push_back(packedLsd);
  out.push_back(0);
  out.push_back(0);
  if (gctCount > 0) {
    out.insert(out.end(), spec.gct.begin(), spec.gct.end());
    out.resize(out.size() + static_cast<size_t>((gctSlots - gctCount) * 3), 0);
  }
  if (spec.transparent >= 0) {
    out.push_back(0x21);
    out.push_back(0xF9);
    out.push_back(0x04);
    out.push_back(0x01);
    out.push_back(0);
    out.push_back(0);
    out.push_back(static_cast<uint8_t>(spec.transparent));
    out.push_back(0);
  }
  out.push_back(0x2C);
  appendU16(out, 0);
  appendU16(out, 0);
  appendU16(out, static_cast<uint16_t>(spec.width));
  appendU16(out, static_cast<uint16_t>(spec.height));
  uint8_t packedImg = 0;
  if (spec.interlaced) {
    packedImg |= 0x40;
  }
  if (lctCount > 0) {
    packedImg |= static_cast<uint8_t>(0x80 | lctBits);
  }
  out.push_back(packedImg);
  if (lctCount > 0) {
    out.insert(out.end(), spec.lct.begin(), spec.lct.end());
    out.resize(out.size() + static_cast<size_t>((lctSlots - lctCount) * 3), 0);
  }
  out.push_back(static_cast<uint8_t>(minCodeSize));
  appendSubBlocks(out, compressed);
  out.push_back(0x3B);
  return out;
}

struct Catcher {
  int width = 0;
  int height = 0;
  bool interlaced = false;
  bool beginCalled = false;
  std::vector<std::vector<uint8_t>> rows;
};

bool onBegin(void* ctx, const gifraster::DecodeInfo& info) {
  auto* catcher = static_cast<Catcher*>(ctx);
  catcher->width = info.width;
  catcher->height = info.height;
  catcher->interlaced = info.interlaced;
  catcher->beginCalled = true;
  catcher->rows.assign(static_cast<size_t>(info.height), std::vector<uint8_t>(static_cast<size_t>(info.width), 0xEE));
  return true;
}

bool onRow(void* ctx, int y, const uint8_t* gray, int width) {
  auto* catcher = static_cast<Catcher*>(ctx);
  if (y < 0 || y >= catcher->height || width != catcher->width) {
    return false;
  }
  catcher->rows[static_cast<size_t>(y)].assign(gray, gray + width);
  return true;
}

gifraster::Status decodeTo(const std::vector<uint8_t>& gif, Catcher& catcher) {
  return gifraster::decodeMemory(gif.data(), gif.size(), onBegin, onRow, &catcher);
}

